export type TranscriptionDoc = { source: string; text: string };
export const EMPTY_TRANSCRIPTION: TranscriptionDoc = { source: DEFAULT_SOURCE, text: "" };

export function normalizeTranscription(value: unknown): TranscriptionDoc {
  const doc = (typeof value === "object" && value !== null ? value : {}) as Partial<TranscriptionDoc>;
  return {
    source: typeof doc.source === "string" ? doc.source : DEFAULT_SOURCE,
    text: typeof doc.text === "string" ? doc.text : "",
  };
}

const store = createBrowserStore<TranscriptionDoc>({
  key: "ritus:transcription",
  empty: EMPTY_TRANSCRIPTION,
  parse: (raw) => raw ? normalizeTranscription(JSON.parse(raw)) : EMPTY_TRANSCRIPTION,
  readError: "cached",
});

export const subscribeTranscription = store.subscribe;
export const getTranscriptionSnapshot = store.getSnapshot;
export const getTranscriptionServerSnapshot = store.getServerSnapshot;
export const saveTranscription = store.save;
